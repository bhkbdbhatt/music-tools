def render_html(report: CertificationReport) -> str:
    tier = report.tier
    cards: List[str] = []
    for p in report.platforms:
        status = "pass" if p.passed else "fail"
        badge = "PASS" if p.passed else "FAIL"
        m = p.metrics
        battery_html = f"<div><label>Battery</label><b>{m.battery_drain_mw} mW</b></div>" if m.battery_drain_mw else ""
        cards.append(
            f"""
      <div class="card {status}">
        <div class="card-head">
          <span class="plat">{p.platform}</span>
          <span class="badge {status}">{badge}</span>
        </div>
        <div class="score">{p.score}<span>/100</span></div>
        <div class="metrics">
          <div><label>Memory</label><b>{m.memory_footprint_mb} MB</b></div>
          <div><label>Latency</label><b>{m.audio_thread_latency_ms} ms</b></div>
          <div><label>CPU</label><b>{m.cpu_audio_pct}%</b></div>
          <div><label>Stream</label><b>{m.streaming_bandwidth_kbps} kbps</b></div>
          {battery_html}
        </div>
        <div class="counts">{p.fail_count} fail · {p.warn_count} warn</div>
      </div>"""
        )

    recs: List[str] = []
    for r in report.recommendations:
        savings: List[str] = []
        if r.estimated_savings_mb:
            savings.append(f"~{r.estimated_savings_mb}MB")
        if r.estimated_savings_kbps:
            savings.append(f"~{r.estimated_savings_kbps}kbps")
        if r.estimated_latency_ms:
            savings.append(f"~{r.estimated_latency_ms}ms")
        meta = f"{'saves ' + ', '.join(savings) + ' · ' if savings else ''}effort: {r.effort} · {', '.join(r.platform_targets)}"
        recs.append(
            f"""<li class="rec">
        <div class="rec-title">{_esc(r.title)}</div>
        <div class="rec-meta">{meta}</div>
        <div class="rec-detail">{_esc(r.detail)}</div>
      </li>"""
        )

    detail: List[str] = []
    for p in report.platforms:
        badge = "pass" if p.passed else "fail"
        badge_text = "PASS" if p.passed else "FAIL"
        if p.violations:
            violations_html = (
                f'<ul class="violations">'
                + "".join(f'<li class="{v.severity}">{_esc(v.message)}</li>' for v in p.violations)
                + "</ul>"
            )
        else:
            violations_html = '<p class="muted">No budget violations.</p>'
        detail.append(
            f"""<section class="pdetail">
        <h3>{p.platform} <span class="badge {badge}">{badge_text}</span></h3>
        <table><thead><tr><th>Metric</th><th>Actual</th><th>Budget</th></tr></thead><tbody>{_metric_rows(p)}</tbody></table>
        {violations_html}
      </section>"""
        )

    overall_cls = "pass" if report.overall_pass else "fail"
    overall_text = "CERTIFIED PASS" if report.overall_pass else "NOT CERTIFIED FAIL"
    s = report.summary
    recs_html = "".join(recs) or '<li class="muted">No fixes required.</li>'

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>Audio Certification — {_esc(report.project.name)}</title>
<style>{_STYLE}</style></head>
<body>
<div class="header">
  <div>
    <h1>Audio Certification — {_esc(report.project.name)}</h1>
    <div class="muted">Engine: {report.project.engine} · Runner: {report.runner.name} ({report.runner.duration_ms}ms) · Tier: {tier} · {_esc(report.created_at)}</div>
  </div>
  <div class="overall {overall_cls}">
    {overall_text} · {s.passed_platforms}/{s.total_platforms} platforms
  </div>
</div>
<div class="cards">{"".join(cards)}</div>
<div class="grid2">
  <div>
    <h3>Recommended fixes</h3>
    <ul class="recs">{recs_html}</ul>
  </div>
  <div>
    <h3>Per-platform detail</h3>
    {"".join(detail)}
  </div>
</div>
<footer class="muted" style="margin-top:24px;font-size:12px">Generated by audiosure v{VERSION} · report {report.id}</footer>
</body></html>"""
