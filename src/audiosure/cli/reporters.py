from __future__ import annotations

import json
from html import escape as _html_escape
from typing import Any, Dict, List

from audiosure.core.types import CertificationReport, MetricsSnapshot, PlatformCertification, to_jsonable

VERSION = "0.1.0"

LABELS: Dict[str, str] = {
    "memoryFootprintMB": "Audio memory (MB)",
    "inMemoryMB": "In-memory media (MB)",
    "streamedMB": "Streamed media (MB)",
    "audioThreadLatencyMs": "Audio thread latency (ms)",
    "cpuAudioPct": "Audio CPU (%)",
    "gpuDspPct": "DSP/GPU (%)",
    "streamingBandwidthKbps": "Streaming bandwidth (kbps)",
    "batteryDrainMw": "Battery drain (mW)",
    "peakConcurrentVoices": "Peak voices",
    "clipCount": "Clip count",
}

SEV_ICON = {"fail": "FAIL", "warn": "WARN", "info": "INFO"}


def _label(m: str) -> str:
    return LABELS.get(m, m)


def render_json(report: CertificationReport) -> str:
    return json.dumps(to_jsonable(report), indent=2)


def render_markdown(report: CertificationReport) -> str:
    lines: List[str] = []
    tier = report.tier
    lines.append(f"# Audio Certification Report — {report.project.name}")
    lines.append("")
    lines.append(
        f"**Generated:** {report.created_at}  |  **Engine:** {report.project.engine}  |  "
        f"**Runner:** {report.runner.name} ({report.runner.duration_ms}ms)  |  **Tier:** {tier}"
    )
    overall = "PASS" if report.overall_pass else "FAIL"
    s = report.summary
    lines.append(
        f"**Overall:** {overall} — {s.passed_platforms}/{s.total_platforms} platforms passed, "
        f"{s.total_fail} failures, {s.total_warn} warnings"
    )
    lines.append("")

    lines.append("## Platform summary")
    lines.append("")
    lines.append("| Platform | Result | Score | Audio mem | Latency | CPU | Stream | Battery | Fails | Warns |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for p in report.platforms:
        m = p.metrics
        battery = f"{m.battery_drain_mw} mW" if m.battery_drain_mw else "n/a"
        lines.append(
            f"| {p.platform} | {'PASS' if p.passed else 'FAIL'} | {p.score} | {m.memory_footprint_mb} MB | "
            f"{m.audio_thread_latency_ms} ms | {m.cpu_audio_pct}% | {m.streaming_bandwidth_kbps} kbps | "
            f"{battery} | {p.fail_count} | {p.warn_count} |"
        )
    lines.append("")

    if any(p.violations for p in report.platforms):
        lines.append("## Budget violations")
        lines.append("")
        for p in report.platforms:
            if not p.violations:
                continue
            lines.append(f"### {p.platform} — {'warnings' if p.passed else 'FAIL'}")
            for v in p.violations:
                lines.append(f"- **[{SEV_ICON[v.severity]}]** {v.message}")
            lines.append("")

    if report.recommendations:
        lines.append("## Recommended fixes (priority order)")
        lines.append("")
        for i, r in enumerate(report.recommendations):
            savings: List[str] = []
            if r.estimated_savings_mb:
                savings.append(f"~{r.estimated_savings_mb}MB")
            if r.estimated_savings_kbps:
                savings.append(f"~{r.estimated_savings_kbps}kbps")
            if r.estimated_latency_ms:
                savings.append(f"~{r.estimated_latency_ms}ms")
            lines.append(f"### {i + 1}. {r.title}")
            lines.append("")
            meta = f"Effort: {r.effort} · Platforms: {', '.join(r.platform_targets)}"
            if savings:
                lines.append(f"*Estimated savings: {', '.join(savings)} · {meta}*")
            else:
                lines.append(f"*{meta}*")
            lines.append("")
            lines.append(r.detail)
            lines.append("")

    lines.append("## Per-platform metrics vs budget")
    lines.append("")
    for p in report.platforms:
        lines.append(f"### {p.platform}")
        lines.append("")
        lines.append("| Metric | Actual | Budget |")
        lines.append("| --- | --- | --- |")
        for key, v in p.metrics.to_dict().items():
            viol = next((x for x in p.violations if x.metric == key), None)
            budget = f"{viol.budget} {viol.unit}" if viol else "-"
            lines.append(f"| {_label(key)} | {v} | {budget} |")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(f"_Generated by audiosure v{VERSION} · report id {report.id}_")
    lines.append("")
    return "\n".join(lines)


def _esc(s: str) -> str:
    return _html_escape(str(s), quote=False)


def _metric_rows(p: PlatformCertification) -> str:
    rows: List[str] = []
    for k, v in p.metrics.to_dict().items():
        viol = next((x for x in p.violations if x.metric == k), None)
        cls = ""
        if viol:
            cls = "val-fail" if viol.severity == "fail" else "val-warn"
        budget = f"{viol.budget} {viol.unit}" if viol else "—"
        rows.append(f"<tr><td>{_esc(_label(k))}</td><td class=\"{cls}\">{v}</td><td class=\"muted\">{budget}</td></tr>")
    return "".join(rows)


